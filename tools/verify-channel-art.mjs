import { randomUUID } from "node:crypto";
import { mkdtemp, readFile, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { pathToFileURL } from "node:url";

import sharp from "sharp";

import {
  CHANNEL_ART,
  MAX_SERVED_BYTES,
  SERVED_SIZE,
  SOURCE_SIZE,
  buildDerivative,
  parseManifest,
  servedPathToArt,
  sha256,
} from "./lib/channel-art.mjs";

function assertConfiguredChannels(channels) {
  if (!Array.isArray(channels) || channels.length !== CHANNEL_ART.length) {
    throw new Error(`Configured channels must contain exactly ${CHANNEL_ART.length} entries`);
  }

  for (const [index, descriptor] of CHANNEL_ART.entries()) {
    const channel = channels[index];
    if (
      channel?.handle !== descriptor.handle ||
      channel?.name !== descriptor.name ||
      channel?.art !== servedPathToArt(descriptor.servedPath)
    ) {
      throw new Error(
        `Configured channel artwork mismatch at index ${index}; expected ${descriptor.handle} -> ${descriptor.artPath}`,
      );
    }
  }
}

async function importConfiguredChannels(root, channelsModulePath) {
  const url = pathToFileURL(join(root, channelsModulePath));
  url.searchParams.set("channel-art-verification", randomUUID());
  const module = await import(url.href);
  return module.CHANNELS;
}

function assertMetadata(metadata, { format, size, handle, kind }) {
  if (metadata.format !== format) {
    throw new Error(
      `${kind} format mismatch for ${handle}: expected ${format === "jpeg" ? "JPEG" : "WebP"}, received ${metadata.format ?? "unknown"}`,
    );
  }
  if (metadata.width !== size || metadata.height !== size) {
    throw new Error(
      `${kind} dimension mismatch for ${handle}: expected ${size}x${size}, received ${metadata.width}x${metadata.height}`,
    );
  }
}

export async function verifyChannelAssets({
  root = process.cwd(),
  manifestPath = "brand/reference/channels/SOURCE.md",
  channelsModulePath = "src/content/channels.ts",
  configuredChannels,
  buildDerivativeFn = buildDerivative,
  temporaryParent = tmpdir(),
} = {}) {
  const markdown = await readFile(join(root, manifestPath), "utf8");
  const manifest = parseManifest(markdown, { phase: "final" });
  const channels =
    configuredChannels ?? (await importConfiguredChannels(root, channelsModulePath));
  assertConfiguredChannels(channels);

  const temporaryDirectory = await mkdtemp(join(temporaryParent, "channel-art-verify-"));
  try {
    for (const channel of manifest.channels) {
      const originalPath = join(root, channel.original.path);
      const servedPath = join(root, channel.served.path);
      const [originalBytes, servedBytes, originalMetadata, servedMetadata] = await Promise.all([
        readFile(originalPath),
        readFile(servedPath),
        sharp(originalPath).metadata(),
        sharp(servedPath).metadata(),
      ]);

      assertMetadata(originalMetadata, {
        format: "jpeg",
        size: SOURCE_SIZE,
        handle: channel.handle,
        kind: "Original",
      });
      assertMetadata(servedMetadata, {
        format: "webp",
        size: SERVED_SIZE,
        handle: channel.handle,
        kind: "Served",
      });

      if (sha256(originalBytes) !== channel.original.sha256) {
        throw new Error(`Original hash mismatch for ${channel.handle}`);
      }
      if (servedBytes.byteLength > MAX_SERVED_BYTES) {
        throw new Error(`Served file exceeds ${MAX_SERVED_BYTES} bytes for ${channel.handle}`);
      }
      if (servedBytes.byteLength !== channel.served.bytes) {
        throw new Error(
          `Served size mismatch for ${channel.handle}: expected ${channel.served.bytes}, received ${servedBytes.byteLength}`,
        );
      }
      if (sha256(servedBytes) !== channel.served.sha256) {
        throw new Error(`Served hash mismatch for ${channel.handle}`);
      }

      const regeneratedPath = join(temporaryDirectory, `${channel.handle}.webp`);
      await buildDerivativeFn(originalPath, regeneratedPath);
      const regeneratedBytes = await readFile(regeneratedPath);
      if (!servedBytes.equals(regeneratedBytes)) {
        throw new Error(`Regenerated bytes differ from the committed derivative for ${channel.handle}`);
      }
    }
  } finally {
    await rm(temporaryDirectory, { recursive: true, force: true });
  }

  return { verified: manifest.channels.length };
}

export async function main() {
  const result = await verifyChannelAssets();
  console.log(`Verified ${result.verified} channel artwork derivatives.`);
}

const isDirectExecution =
  process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href;
if (isDirectExecution) {
  main().catch((error) => {
    console.error(error instanceof Error ? error.message : error);
    process.exitCode = 1;
  });
}
